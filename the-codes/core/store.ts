/**
 * SQLite-backed job store. Node builtin `node:sqlite`, no dependencies.
 *
 * The store is the single source of truth for the whole system (see
 * docs/ARCHITECTURE.md): provider readers write here, surfaces read from here
 * and react to changes via core/bus.ts. Two surfaces therefore cost one
 * implementation, which is the point of the layered design.
 *
 * Schema notes worth defending in review:
 *
 * - Timestamps are ISO-8601 TEXT, never INTEGER epoch. They sort correctly as
 *   text (fixed-width UTC format, so lexicographic == chronological), they are
 *   readable in a `sqlite3` dump, and range queries on `lastEventAt` are plain
 *   string comparisons.
 * - `events` has no FK-enforced cascade from `jobs` on purpose. Pruning walks
 *   events first, then jobs, in one transaction (see `prune`), which keeps the
 *   delete explicit and observable instead of hidden in a cascade.
 * - Job rows are replaced wholesale on upsert rather than patched field by
 *   field. A reader re-saving a job produces exactly one row and cannot leave
 *   half a job behind. The trade-off is that concurrent writers for the same job
 *   id lose updates; in practice a job id has one owner (its provider reader),
 *   and adding merge logic for a case that does not exist would be the kind of
 *   clever abstraction that makes the next bug harder to find.
 */

import { DatabaseSync } from 'node:sqlite';
import type { Job, JobEvent, JobFilter } from './types.ts';
import { isProgressEvent, isTerminalStatus } from './types.ts';
import type { EventBus } from './bus.ts';

const SCHEMA = `
CREATE TABLE IF NOT EXISTS jobs (
  id            TEXT PRIMARY KEY,
  title         TEXT NOT NULL,
  provider      TEXT NOT NULL,
  status        TEXT NOT NULL,
  stage         TEXT,
  cwd           TEXT,
  pid           INTEGER,
  task          TEXT,
  started_at    TEXT NOT NULL,
  updated_at    TEXT NOT NULL,
  last_event_at TEXT NOT NULL,
  ended_at      TEXT,
  activity      TEXT,
  warnings      TEXT NOT NULL DEFAULT '[]',
  metrics       TEXT
);

CREATE TABLE IF NOT EXISTS events (
  job_id         TEXT NOT NULL,
  seq            INTEGER NOT NULL,
  at             TEXT NOT NULL,
  kind           TEXT NOT NULL,
  message        TEXT NOT NULL,
  tool           TEXT,
  tool_input_hash TEXT,
  data           TEXT,
  PRIMARY KEY (job_id, seq)
);

CREATE INDEX IF NOT EXISTS idx_jobs_last_event_at ON jobs (last_event_at);
CREATE INDEX IF NOT EXISTS idx_jobs_status        ON jobs (status);
CREATE INDEX IF NOT EXISTS idx_jobs_provider      ON jobs (provider);
CREATE INDEX IF NOT EXISTS idx_events_at          ON events (at);
`;

/** Job with defaults applied, as returned by reads. */
export interface JobStoreOptions {
  /** File path, or ':memory:' for a throwaway store (tests). */
  path?: string;
  /** Bus to publish changes on. Optional: a store with no bus is valid for batch jobs. */
  bus?: EventBus;
  /** Verbose SQL logging to stderr. */
  verbose?: boolean;
}

/** Result of a prune sweep. */
export interface PruneResult {
  /** Jobs removed. */
  jobs: number;
  /** Events removed alongside them. */
  events: number;
}

export class JobStore {
  #db: DatabaseSync;
  #bus: EventBus | undefined;
  #busy = false;

  constructor(options: JobStoreOptions = {}) {
    this.#db = new DatabaseSync(options.path ?? ':memory:');
    if (options.verbose) this.#db.exec('PRAGMA verbose = 1');
    // NORMAL is the standard WAL durability trade: survives process crash,
    // may lose the last transactions on OS crash. For a liveness monitor whose
    // data is regenerated by re-reading worker state, that is entirely
    // acceptable and much faster than FULL.
    this.#db.exec('PRAGMA journal_mode = WAL');
    this.#db.exec('PRAGMA synchronous = NORMAL');
    this.#db.exec(SCHEMA);
    this.#bus = options.bus;
  }

  /**
   * Run a write in a transaction.
   *
   * Node's SQLite is synchronous, so there is no interleaving hazard between
   * callers — there is only re-entrancy: `upsertJob` publishes on the bus, and a
   * subscriber may reasonably call back into the store. A nested call therefore
   * joins the already-open transaction instead of opening a nested one, which
   * SQLite would reject. Joining is correct because the outer COMMIT covers the
   * inner work, and it needs no queue: the re-entrant call runs inline to
   * completion before the outer function continues.
   */
  #tx<T>(fn: () => T): T {
    if (this.#busy) return fn();
    this.#busy = true;
    try {
      this.#db.exec('BEGIN IMMEDIATE');
      const result = fn();
      this.#db.exec('COMMIT');
      return result;
    } catch (error) {
      try {
        this.#db.exec('ROLLBACK');
      } catch {
        // A rollback failure means the transaction was already unwound. The
        // original error is the useful one; rethrowing this would only bury it.
      }
      throw error;
    } finally {
      this.#busy = false;
    }
  }

  /**
   * Insert or replace a job row, and publish `job.upserted`.
   *
   * `lastEventAt` is bumped to `updatedAt` only when the caller did not supply
   * it. That default is the important part: a reader that re-saves an unchanged
   * job without new information will not advance the progress clock, which is
   * what keeps a dead worker from looking alive (see Job.lastEventAt).
   */
  upsertJob(job: Job): Job {
    const stored: Job = {
      ...job,
      lastEventAt: job.lastEventAt ?? job.updatedAt,
      warnings: job.warnings ?? [],
    };
    if (isTerminalStatus(stored.status) && stored.endedAt === undefined) {
      stored.endedAt = stored.updatedAt;
    }

    this.#tx(() => {
      this.#db
        .prepare(
          `INSERT INTO jobs
             (id, title, provider, status, stage, cwd, pid, task,
              started_at, updated_at, last_event_at, ended_at,
              activity, warnings, metrics)
           VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
           ON CONFLICT(id) DO UPDATE SET
             title=excluded.title, provider=excluded.provider,
             status=excluded.status, stage=excluded.stage, cwd=excluded.cwd,
             pid=excluded.pid, task=excluded.task,
             started_at=excluded.started_at, updated_at=excluded.updated_at,
             last_event_at=excluded.last_event_at, ended_at=excluded.ended_at,
             activity=excluded.activity, warnings=excluded.warnings,
             metrics=excluded.metrics`,
        )
        .run(
          stored.id,
          stored.title,
          stored.provider,
          stored.status,
          stored.stage ?? null,
          stored.cwd ?? null,
          stored.pid ?? null,
          stored.task ?? null,
          stored.startedAt,
          stored.updatedAt,
          stored.lastEventAt,
          stored.endedAt ?? null,
          stored.activity ? JSON.stringify(stored.activity) : null,
          JSON.stringify(stored.warnings),
          stored.metrics ? JSON.stringify(stored.metrics) : null,
        );
    });

    this.#bus?.publish('job.upserted', stored);
    return stored;
  }

  /** One job by id, or null. */
  getJob(id: string): Job | null {
    const row = this.#db
      .prepare('SELECT * FROM jobs WHERE id = ?')
      .get(id) as unknown as Row | undefined;
    return row ? rowToJob(row) : null;
  }

  /**
   * Jobs matching a filter, newest activity first.
   *
   * Ordering is by `last_event_at` DESC because a surface's default view is "what
   * is happening now" — a job that last moved 10 minutes ago belongs below one
   * that moved 5 seconds ago, regardless of when each started.
   */
  listJobs(filter: JobFilter = {}): Job[] {
    const where: string[] = [];
    const params: Array<string | number> = [];

    if (filter.provider !== undefined) {
      where.push('provider = ?');
      params.push(filter.provider);
    }
    if (filter.status !== undefined) {
      where.push('status = ?');
      params.push(filter.status);
    }
    if (filter.stage !== undefined) {
      where.push('stage = ?');
      params.push(filter.stage);
    }
    if (filter.activeSince !== undefined) {
      where.push('last_event_at >= ?');
      params.push(filter.activeSince);
    }
    if (filter.search !== undefined) {
      // LIKE wildcards in user input are escaped so a search for "100%" matches
      // that literal text rather than everything. SQLite has no default escape
      // character, so ESCAPE has to be declared explicitly.
      where.push(`(title LIKE ? ESCAPE '\\' OR id LIKE ? ESCAPE '\\')`);
      const like = `%${filter.search.replace(/[%_]/g, (c) => `\\${c}`)}%`;
      params.push(like, like);
    }

    const sql =
      'SELECT * FROM jobs' +
      (where.length ? ` WHERE ${where.join(' AND ')}` : '') +
      ' ORDER BY last_event_at DESC' +
      // Hard cap: a surface must never be handed the whole history. 500 covers
      // the 16-concurrent-job case from the architecture with room to spare.
      (filter.limit === undefined ? ' LIMIT 500' : ` LIMIT ${Math.max(1, filter.limit | 0)}`);

    const rows = this.#db.prepare(sql).all(...params) as unknown as Row[];
    return rows.map(rowToJob);
  }

  /**
   * Append an event and, if it proves progress, advance the job's `lastEventAt`.
   *
   * The advance happens only for progress kinds (`tool_call`, `message`). See the
   * EventKind doc comment for why that boundary lives on the union.
   *
   * Events are accepted for a job id that has no row yet. A reader often sees a
   * transcript before it has parsed enough to build a Job, and dropping those
   * early events would leave the audit trail with a hole exactly where the
   * diagnosis is hardest. The orphaned events are picked up when the job is
   * first upserted, or swept by `prune`.
   */
  appendEvent(event: JobEvent): JobEvent {
    // Normalized to the shape `recentEvents` will return, so what a caller gets
    // back from a write is deepEqual to what a later read produces. `tool` and
    // `toolInputHash` are declared `?: string | null`, and SQL NULL is the
    // natural "absent" — the alternative (dropping the key) would make the
    // returned object and the read-back object differ structurally.
    const stored: JobEvent = { tool: null, toolInputHash: null, ...event };

    this.#tx(() => {
      if (stored.seq === undefined) {
        const max = this.#db
          .prepare('SELECT MAX(seq) AS s FROM events WHERE job_id = ?')
          .get(stored.jobId) as unknown as { s: number | null } | undefined;
        // Number() because node:sqlite types MAX() as number | bigint. SQLite
        // never returns bigint here, but the coercion keeps the arithmetic total.
        stored.seq = Number(max?.s ?? 0) + 1;
      }
      this.#db
        .prepare(
          `INSERT OR REPLACE INTO events
             (job_id, seq, at, kind, message, tool, tool_input_hash, data)
           VALUES (?, ?, ?, ?, ?, ?, ?, ?)`,
        )
        .run(
          stored.jobId,
          stored.seq,
          stored.at,
          stored.kind,
          stored.message,
          stored.tool ?? null,
          stored.toolInputHash ?? null,
          stored.data ? JSON.stringify(stored.data) : null,
        );

      if (isProgressEvent(stored.kind)) {
        // Guarded on `at >= last_event_at` so an out-of-order or clock-skewed
        // event cannot move the clock backwards and make a job look stalled
        // while it is mid-step.
        this.#db
          .prepare(
            `UPDATE jobs SET last_event_at = ?
              WHERE id = ? AND last_event_at <= ?`,
          )
          .run(stored.at, stored.jobId, stored.at);
      }
    });

    this.#bus?.publish('event.appended', stored);
    return stored;
  }

  /**
   * The `n` most recent events for a job, oldest first.
   *
   * Ascending order on the way out, because every consumer wants chronological:
   * the mod renders a tail, and `detectToolLoop` scans the tail backwards.
   */
  recentEvents(jobId: string, n = 50): JobEvent[] {
    const rows = this.#db
      .prepare('SELECT * FROM events WHERE job_id = ? ORDER BY seq DESC LIMIT ?')
      .all(jobId, Math.max(1, n | 0)) as unknown as Row[];
    return rows.reverse().map(rowToEvent);
  }

  /**
   * Delete jobs whose `last_event_at` is older than `olderThanMs` before `now`,
   * along with all of their events.
   *
   * One transaction, events before jobs: the ordering is only meaningful for
   * correctness if a FK is later added, but it also means a partial prune can
   * never leave an event pointing at nothing.
   *
   * The job's terminal status is irrelevant here — a job finished two days ago
   * has the same retention value as one that died two days ago.
   */
  prune(olderThanMs: number, now: Date | string | number = new Date()): PruneResult {
    const current = now instanceof Date ? now.getTime() : typeof now === 'number' ? now : Date.parse(now);
    const cutoff = new Date(current - olderThanMs).toISOString();

    const result = this.#tx((): PruneResult => {
      const stale = this.#db
        .prepare('SELECT id FROM jobs WHERE last_event_at < ?')
        .all(cutoff) as unknown as Array<{ id: string }>;

      const delEvents = this.#db.prepare('DELETE FROM events WHERE job_id = ?');
      const delJob = this.#db.prepare('DELETE FROM jobs WHERE id = ?');
      let events = 0;
      for (const { id } of stale) {
        events += Number(delEvents.run(id).changes);
        delJob.run(id);
      }
      // Orphans: events for jobs that never got a row. They accumulate from
      // readers that see a transcript before they can build a Job, and nothing
      // else would ever clear them, so they are swept on the same cutoff. This
      // runs even when no job rows were stale — otherwise pruning early-exits
      // and orphan events live forever.
      const orphanEvents = this.#db
        .prepare(
          `DELETE FROM events
            WHERE at < ?
              AND job_id NOT IN (SELECT id FROM jobs)`,
        )
        .run(cutoff).changes;
      // Number() for the same reason as above: node:sqlite types `changes` as
      // number | bigint.
      const totalOrphans = Number(orphanEvents);

      return { jobs: stale.length, events: events + totalOrphans };
    });

    // Published outside the transaction: a subscriber that queries the store on
    // this event must see the post-commit state, not the one mid-delete.
    this.#bus?.publish('pruned', result);
    return result;
  }

  /** Close the database. Idempotent. */
  close(): void {
    this.#db.close();
  }
}

/**
 * Raw row shape. Kept private; only rowToJob/rowToEvent interpret it.
 *
 * `node:sqlite` types rows as `Record<string, SQLOutputValue>`, which says
 * nothing about which columns exist or what they hold — so the real shape is
 * declared here and asserted at the boundary via `as unknown as Row`. The
 * `unknown` hop is not laziness: `node:sqlite` genuinely cannot check it, and
 * pretending otherwise with a narrower Row would just move the same unchecked
 * cast somewhere less obvious.
 */
interface Row {
  id: string;
  title: string;
  provider: string;
  status: string;
  stage: string | null;
  cwd: string | null;
  pid: number | null;
  task: string | null;
  started_at: string;
  updated_at: string;
  last_event_at: string;
  ended_at: string | null;
  activity: string | null;
  warnings: string;
  metrics: string | null;
  job_id: string;
  seq: number;
  at: string;
  kind: string;
  message: string;
  tool: string | null;
  tool_input_hash: string | null;
  data: string | null;
}

/**
 * Rebuild a Job from a row.
 *
 * Optional fields are omitted from the object rather than set to `undefined`
 * when the column is NULL. Under `exactOptionalPropertyTypes` that is also the
 * only type-correct option, and it keeps a round-tripped Job `deepEqual` to what
 * the caller wrote — `{id, title}` should not come back carrying `metrics:
 * undefined`.
 */
function rowToJob(row: Row): Job {
  return {
    id: row.id,
    title: row.title,
    provider: row.provider,
    status: row.status as Job['status'],
    stage: row.stage,
    cwd: row.cwd,
    pid: row.pid,
    task: row.task,
    startedAt: row.started_at,
    updatedAt: row.updated_at,
    lastEventAt: row.last_event_at,
    endedAt: row.ended_at,
    activity: row.activity === null ? null : (JSON.parse(row.activity) as Job['activity']),
    warnings: row.warnings === '' ? [] : (JSON.parse(row.warnings) as NonNullable<Job['warnings']>),
    ...(row.metrics === null ? {} : { metrics: JSON.parse(row.metrics) as Record<string, number> }),
  };
}

/** Rebuild a JobEvent from a row. Same omit-rather-than-undefined rule. */
function rowToEvent(row: Row): JobEvent {
  return {
    jobId: row.job_id,
    seq: row.seq,
    at: row.at,
    kind: row.kind as JobEvent['kind'],
    message: row.message,
    tool: row.tool,
    toolInputHash: row.tool_input_hash,
    ...(row.data === null ? {} : { data: JSON.parse(row.data) as Record<string, unknown> }),
  };
}