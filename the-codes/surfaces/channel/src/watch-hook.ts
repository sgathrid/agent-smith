/**
 * PostToolUse (asyncRewake) hook entrypoint.
 *
 * Reads the hook JSON from stdin; for spawn_job / resume_job / run_pipeline it
 * watches the new job/run in-process until it is terminal, writes the milestone
 * line(s) to stderr and exits 2 so Claude is woken. Anything else, any error:
 * exit 0 silently. A hook must never break the session.
 */

import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { existsSync, realpathSync } from 'node:fs';
import { readAcceptance } from '../../../forge/checks.ts';
import { claimMarkerPath, parseLaunches, unwrapResponse } from '../../mod/hooks/notice.ts';
import { type JobWatchOptions, runJobWatch } from './monitor.ts';

/** Longest job a spawn may request (forge MAX_TIMEOUT_MS = 6h). */
const MAX_WATCH_JOB_MS = 6 * 60 * 60_000;

/** hooks/watch-hooks.json `timeout` (21900 s, generated by scripts/build-plugin.mjs) less a minute: the watcher must end first. */
const HOOK_TIMEOUT_MS = 21_900_000;
const WATCH_CAP_MS = HOOK_TIMEOUT_MS - 60_000;
const WATCH_GRACE_MS = 60_000;

export interface WatchTarget {
  readonly kind: 'job' | 'run';
  /** The first id; `ids` holds every one a variants ack started. */
  readonly id: string;
  readonly ids: readonly string[];
  readonly cwd: string;
  /**
   * Watch budget: the job's own timeout (from the ack), plus the acceptance budget its checks may take
   * (from the pending placeholder written at spawn), plus a minute, capped below the hook's own timeout.
   * Pipelines get the 6h job cap.
   */
  readonly timeoutMs: number;
}

export { unwrapResponse };

const isObj = (v: unknown): v is Record<string, unknown> => v !== null && typeof v === 'object' && !Array.isArray(v);

/**
 * Decide what (if anything) to watch from a parsed hook input. The ack parsing
 * is the mod's (notice.ts parseLaunch), so both announcers agree on what a
 * launch started; only the cwd fallbacks are the hook's own.
 */
export function parseHookInput(input: unknown): WatchTarget | null {
  if (!isObj(input)) return null;
  const launches = parseLaunches(input['tool_name'], input['tool_response']);
  const launch = launches[0];
  if (launch === undefined) return null;
  let cwd = launch.repo;
  if (cwd === null && typeof input['cwd'] === 'string' && input['cwd'].length > 0) cwd = input['cwd'];
  if (cwd === null) cwd = process.cwd();
  const resolved = path.resolve(cwd);
  // One watch for all of them: it lasts as long as the longest job's budget.
  const timeoutMs = Math.max(...launches.map((l) => {
    const budget = l.kind === 'job' ? pendingBudgetMs(resolved, l.id) : 0;
    return Math.min(WATCH_CAP_MS, (l.timeoutMs ?? MAX_WATCH_JOB_MS) + budget + WATCH_GRACE_MS);
  }));
  return { kind: launch.kind, id: launch.id, ids: launches.map((l) => l.id), cwd: resolved, timeoutMs };
}

function pendingBudgetMs(cwd: string, jobId: string): number {
  try {
    const b = (readAcceptance(cwd, jobId) as { pending?: boolean; budgetMs?: unknown }).budgetMs;
    return typeof b === 'number' && b > 0 ? b : 0;
  } catch { return 0; }
}

/** Run the hook. Resolves to the process exit code (2 = wake Claude). */
export async function runHook(
  stdin: string,
  write: (line: string) => void,
  options: Partial<JobWatchOptions> = {},
): Promise<number> {
  try {
    const target = parseHookInput(JSON.parse(stdin) as unknown);
    if (target === null) return 0;
    const perId = await Promise.all(target.ids.map(async (id) => {
      const lines: string[] = [];
      await runJobWatch({
        timeoutMs: target.timeoutMs,
        ...options,
        cwd: target.cwd,
        jobIds: target.kind === 'job' ? [id] : [],
        runIds: target.kind === 'run' ? [id] : [],
        onError: () => {},
        // A hook wakes Claude once (exit 2 with stderr), so it announces once: the verdict, or
        // "exited · checks running" if the acceptance budget runs out first. The mod sends both.
        announceOnce: true,
        // The notice as written, line breaks kept; the timeout line has no batch.
        emit: (line, batch) => { lines.push(batch?.content ?? line); },
      });
      return { id, lines };
    }));
    // Drop lines for any job/run whose claim marker exists when the hook writes (e.g. a cancelled variant).
    const lines = perId.flatMap(({ id, lines: idLines }) => (claimed(target.cwd, target.kind, id) ? [] : idLines));
    if (lines.length === 0) return 0;
    // Exit 2 is the wake protocol, and the host labels it "Stop hook feedback".
    // This path runs only without the mod (which claims the job and announces it
    // itself), so say plainly that it is a notice, not an error.
    write(lines.join('\n') + '\n(notice, not an error)\n');
    return 2;
  } catch {
    return 0;
  }
}

/**
 * The mod writes the marker under the repo path it was configured with; the
 * ack may spell the same repo differently (a symlinked /tmp, say), so check
 * the canonical path as well.
 */
function claimed(cwd: string, kind: 'job' | 'run', id: string): boolean {
  if (existsSync(claimMarkerPath(cwd, kind, id))) return true;
  try { return existsSync(claimMarkerPath(realpathSync(cwd), kind, id)); } catch { return false; }
}

async function readStdin(): Promise<string> {
  const chunks: Buffer[] = [];
  for await (const chunk of process.stdin) chunks.push(Buffer.from(chunk as Buffer));
  return Buffer.concat(chunks).toString('utf8');
}

function isEntrypoint(): boolean {
  const invoked = process.argv[1];
  return invoked !== undefined && path.resolve(invoked) === fileURLToPath(import.meta.url);
}

if (isEntrypoint()) {
  try {
    const code = await runHook(await readStdin(), (s) => { process.stderr.write(s); });
    process.exitCode = code;
  } catch {
    process.exitCode = 0;
  }
}
