// Stamp the executable entrypoint only after a successful TypeScript build.
import { chmodSync, existsSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const dist = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'dist');
const target = './surfaces/channel/src/server.js';
const entry = path.join(dist, 'server.js');
const emitted = path.join(dist, 'surfaces', 'channel', 'src', 'server.js');
const monitorEmitted = path.join(dist, 'surfaces', 'channel', 'src', 'monitor.js');

const hookEmitted = path.join(dist, 'surfaces', 'channel', 'src', 'watch-hook.js');

// Verify the real build output exists before writing a shim that points at it.
if (!existsSync(emitted)) {
  process.stderr.write(`agent-smith: build did not emit ${emitted}\n`);
  process.exit(1);
}
if (!existsSync(monitorEmitted)) {
  process.stderr.write(`agent-smith: build did not emit ${monitorEmitted}\n`);
  process.exit(1);
}
if (!existsSync(hookEmitted)) {
  process.stderr.write(`agent-smith: build did not emit ${hookEmitted}\n`);
  process.exit(1);
}

writeFileSync(
  entry,
  `#!/usr/bin/env node\n// Generated by scripts/stamp-entrypoint.mjs — do not edit.\n` +
    `// Re-exports the real entrypoint; see that file for the implementation.\n` +
    `import '${target}';\n`,
  'utf8',
);

chmodSync(entry, 0o755);
process.stderr.write(`agent-smith: wrote ${entry} -> ${target}\n`);

const monitorEntry = path.join(dist, 'monitor.js');
writeFileSync(
  monitorEntry,
  `#!/usr/bin/env node\n// Generated by scripts/stamp-entrypoint.mjs — do not edit.\n` +
    `import { startCliMonitor } from './surfaces/channel/src/monitor.js';\n` +
    `await startCliMonitor();\n`,
  'utf8',
);
chmodSync(monitorEntry, 0o755);
process.stderr.write(`agent-smith: wrote ${monitorEntry} -> ${monitorEmitted}\n`);

// The PostToolUse asyncRewake hook entrypoint: reads the hook JSON on stdin and
// exits with runHook's code (2 wakes Claude).
const hookEntry = path.join(dist, 'watch-hook.js');
writeFileSync(
  hookEntry,
  `#!/usr/bin/env node\n// Generated by scripts/stamp-entrypoint.mjs — do not edit.\n` +
    `import { runHook } from './surfaces/channel/src/watch-hook.js';\n` +
    `const chunks = [];\n` +
    `for await (const chunk of process.stdin) chunks.push(Buffer.from(chunk));\n` +
    `process.exitCode = await runHook(Buffer.concat(chunks).toString('utf8'), (s) => { process.stderr.write(s); });\n`,
  'utf8',
);
chmodSync(hookEntry, 0o755);
process.stderr.write(`agent-smith: wrote ${hookEntry} -> ${hookEmitted}\n`);
