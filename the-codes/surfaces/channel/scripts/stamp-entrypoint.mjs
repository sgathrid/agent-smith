/**
 * stamp-entrypoint.mjs — write `dist/server.js`, the path MCP clients are told to run.
 *
 * WHY A POST-BUILD STEP. The channel imports `../../../harness/*.ts` and
 * `../../mod/hooks/stale.ts` — cross-package imports that are correct in the source
 * tree and correct at runtime. They defeat `rootDir`, so tsc emits into a tree that
 * mirrors the repo layout:
 *
 *   dist/surfaces/channel/src/server.js
 *   dist/harness/agy-staff.js
 *   dist/surfaces/mod/hooks/stale.js
 *
 * That mirrored path is correct but not what anyone should have to type into an MCP
 * config. So this writes a tiny re-export shim at `dist/server.js` and makes it
 * executable, which is the only path `package.json#bin` and the README ever mention.
 *
 * It is a three-line shim rather than a `bin` symlink because MCP clients spawn the
 * file directly and a broken symlink in a published tarball is a worse failure than a
 * two-line file.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * WHY THIS SCRIPT ALSO FAILS THE BUILD
 * ─────────────────────────────────────────────────────────────────────────────
 *
 * `tsc` exits non-zero on `harness/normalize.ts`, which has 8 pre-existing type
 * errors (mutating `readonly` fields). Those are upstream defects in a package this
 * surface imports but MUST NOT modify, and tsc still emits correct JavaScript for
 * them because `noEmitOnError` is not set.
 *
 * So `npm run build` runs `tsc` and then this script regardless, and THIS script is
 * what fails the build — by checking the artifact actually exists. That is a
 * stronger check than an exit code for the failure we care about: a syntax error or
 * a missing file stops the build here, and a tsc exit code polluted by someone
 * else's errors does not.
 *
 * Type errors in THIS package are caught properly by `npm run typecheck`, which is
 * clean. Nothing is being suppressed; the two checks are just ordered so that an
 * upstream lint failure does not block an artifact that is demonstrably fine.
 */

import { chmodSync, existsSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const dist = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'dist');
const target = './surfaces/channel/src/server.js';
const entry = path.join(dist, 'server.js');
const emitted = path.join(dist, 'surfaces', 'channel', 'src', 'server.js');

// Verify the real build output exists before writing a shim that points at it.
if (!existsSync(emitted)) {
  process.stderr.write(`agy-watch: build did not emit ${emitted}\n`);
  process.exit(1);
}

writeFileSync(
  entry,
  `#!/usr/bin/env node\n// Generated by scripts/stamp-entrypoint.mjs — do not edit.\n` +
    `// Re-exports the real entrypoint; see that file for the implementation.\n` +
    `import '${target}';\n`,
  'utf8',
);

chmodSync(entry, 0o755);
process.stderr.write(`agy-watch: wrote ${entry} -> ${target}\n`);